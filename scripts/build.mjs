import {build} from 'esbuild';
import {mkdir,readFile,writeFile,copyFile,cp} from 'node:fs/promises';
import countries from '../datasets/countries.js';
for(const dir of ['www','dist','demo'])await mkdir(dir,{recursive:true});
await build({entryPoints:['app.js'],bundle:true,outfile:'www/app.js',format:'iife',target:'es2020'});
const html=(await readFile('index.html','utf8')).replace('type="module"','defer').replaceAll('href="/style.css"','href="style.css"').replaceAll('src="/app.js"','src="app.js"');
await writeFile('www/index.html',html);
await copyFile('style.css','www/style.css');
await cp('assets','www/assets',{recursive:true});
await mkdir('www/datasets',{recursive:true});
await cp('datasets/hanja','www/datasets/hanja',{recursive:true});
for(const file of ['SOURCES.md','COUNTRIES-LICENSE','country-sources.json'])await copyFile('datasets/'+file,'www/datasets/'+file);
const css=await readFile('style.css','utf8');
const js=await readFile('www/app.js','utf8');
const flags={};
for(const country of countries)flags[country.id]='data:image/svg+xml;base64,'+(await readFile(country.flag)).toString('base64');
const standalone=html.replace('<link rel="stylesheet" href="style.css">',()=>`<style>${css}</style>`);
const single=standalone.replace('<script defer src="app.js"></script>','').replace('</body>',()=>`<script>window.MEMORY_FLAGS=${JSON.stringify(flags)};</script><script>${js}</script></body>`);
await writeFile('dist/chagok-demo.html',single);
await copyFile('dist/chagok-demo.html','demo/index.html');
console.log(`Built web, Android assets and offline demo with ${countries.length} embedded flag images.`);
