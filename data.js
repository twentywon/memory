export function getCards(topic, direction, dynasty='조선') {
 if(topic==='kings') return dynasties[dynasty].map((name,i)=>({id:`${dynasty}-${i}`,left:`${dynasty} ${i+1}대`,right:name}));
 return (topic==='countries'?countries:words).map((item,i)=>{
 let left,right;
 if(topic==='countries') {
 const [flag,name,capital]=item;
 if(direction==='reverse'){left=capital;right=`${flag} ${name}`;}
 else if(direction==='flag'){left=flag;right=`${name} · ${capital}`;}
 else {left=`${flag} ${name}`;right=capital;}
 } else { [left,right]=direction==='reverse'?[item[1],item[0]]:item; }
 return {id:`${topic}-${i}`,left,right};
 });
}
